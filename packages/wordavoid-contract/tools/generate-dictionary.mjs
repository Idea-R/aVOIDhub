import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repositoryRoot = path.resolve(packageRoot, '../..')
const sourcePath = path.join(repositoryRoot, 'games/word-avoid/src/data/words.ts')
const outputPath = path.join(packageRoot, 'src/dictionary.generated.ts')
const arrayNames = ['easyWords', 'mediumWords', 'hardWords', 'extremeWords', 'bossWords']
const source = await readFile(sourcePath, 'utf8')
const entries = []
const seen = new Set()

for (const arrayName of arrayNames) {
  const block = source.match(new RegExp(`export const ${arrayName}: WordData\\[\\] = \\[([\\s\\S]*?)\\n\\];`))
  if (!block) throw new Error(`Could not find ${arrayName} in ${sourcePath}`)

  const entryPattern = /\{\s*text:\s*'([^']+)',\s*difficulty:\s*'([^']+)',\s*category:\s*'([^']+)',\s*complexity:\s*(\d+)\s*\}/g
  for (const match of block[1].matchAll(entryPattern)) {
    const text = match[1]
    const difficulty = match[2]
    const category = match[3]
    const complexity = Number(match[4])
    if (!/^[a-z]+$/.test(text)) throw new Error(`V1 dictionary word is not lowercase ASCII: ${text}`)
    if (!['easy', 'medium', 'hard', 'extreme', 'boss'].includes(difficulty)) {
      throw new Error(`Unknown difficulty ${difficulty} for ${text}`)
    }
    const duplicateKey = `${difficulty}:${text}`
    if (seen.has(duplicateKey)) continue
    seen.add(duplicateKey)
    entries.push({
      id: `wa-${entries.length.toString(36).padStart(4, '0')}`,
      text,
      difficulty,
      category,
      complexity,
    })
  }
}

if (entries.length < 1_000) throw new Error(`Expected at least 1,000 V1 words, found ${entries.length}`)

const canonical = JSON.stringify(entries)
const hash = createHash('sha256').update(canonical).digest('hex')
const counts = Object.fromEntries(arrayNames.map((name) => [name.replace('Words', ''), 0]))
for (const entry of entries) counts[entry.difficulty] += 1

const output = `// Generated by tools/generate-dictionary.mjs from the five competitive word arrays.\n// Do not edit by hand. Run npm run generate:dictionary --workspace=@avoid/wordavoid-contract.\n\nexport type WordAvoidDifficulty = 'easy' | 'medium' | 'hard' | 'extreme' | 'boss'\n\nexport interface WordAvoidDictionaryEntry {\n  id: string\n  text: string\n  difficulty: WordAvoidDifficulty\n  category: string\n  complexity: number\n}\n\nexport const WORDAVOID_DICTIONARY_VERSION = 'wordavoid-dictionary-2026-08-20'\nexport const WORDAVOID_DICTIONARY_HASH = '${hash}'\nexport const WORDAVOID_DICTIONARY_COUNTS = ${JSON.stringify(counts)} as const\n\nexport const WORDAVOID_DICTIONARY = JSON.parse(${JSON.stringify(canonical)}) as readonly WordAvoidDictionaryEntry[]\n`

if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '')
  if (existing !== output) {
    throw new Error('Generated WORDaVOID dictionary is stale. Run the generator and commit the result.')
  }
  console.log(`WORDaVOID dictionary current: ${entries.length} entries, sha256 ${hash}`)
} else {
  await writeFile(outputPath, output, 'utf8')
  console.log(`Generated ${entries.length} WORDaVOID entries with sha256 ${hash}`)
}
